export function fasesCompletadasDe(emprendimiento: EmprendimientoMock): number {
  if (emprendimiento.estado === "terminado") return 12
  const numero = Number.parseInt(emprendimiento.faseNombre, 10)
  return Number.isNaN(numero) ? 0 : numero - 1
}

/**
 * Construye el detalle completo (con ruta resuelta) de un emprendimiento.
 * La usan tanto `/api/emprendimientos/:id` (portal admin) como
 * `/api/mi/emprendimiento` (portal del emprendedor) para no duplicar lógica.
 */
export function construirDetalleEmprendimiento(emprendimiento: EmprendimientoMock): EmprendimientoDetalle {
  const fasesCompletadas = fasesCompletadasDe(emprendimiento)
  const ruta = construirRuta(fasesCompletadas)
  const { etapa, fase } = faseActualDeRuta(ruta)

  return {
    idEmprendimiento: emprendimiento.idEmprendimiento,
    nombreReferencia: emprendimiento.nombreReferencia,
    idEtapaIngreso: 1,
    estado: emprendimiento.estado,
    motivo: emprendimiento.motivo,
    fechaIngreso: emprendimiento.fechaIngreso,
    fechaCulminacion: emprendimiento.estado === "terminado" ? emprendimiento.ultimaActividad : null,
    fechaDesistimiento: null,
    fechaReingreso: null,
    fechaInactividad: emprendimiento.estado === "inactivo" ? emprendimiento.ultimaActividad : null,
    integrantes: emprendimiento.integrantes.map((nombre, i) => {
      const correo = `${nombre.split(" ")[0].toLowerCase()}@unicesmag.edu.co`
      return {
        idUsuario: String(emprendimiento.idEmprendimiento * 10 + i),
        idEmprendimiento: emprendimiento.idEmprendimiento,
        emprendedor: {
          idUsuario: String(emprendimiento.idEmprendimiento * 10 + i),
          nombre,
          correo,
          numeroIdentificacion: "000000000",
          fechaNacimiento: "2000-01-01",
          fechaRegistro: "2026-01-10T00:00:00",
          fechaActualizacion: null,
          usuario: {
            idUsuario: emprendimiento.idEmprendimiento * 10 + i,
            nombre,
            correo,
            idRol: 4,
            activo: true,
            fechaCreacion: "2026-01-10T00:00:00",
          },
        },
      }
    }),
    caracterizacion: emprendimiento.caracterizacion,
    ultimaActividad: emprendimiento.ultimaActividad,
    diagnosticoPendiente: emprendimiento.diagnosticoPendiente,
    fasesCompletadas,
    totalFases: TOTAL_FASES,
    ruta,
    faseActual: {
      idEmprendimientoFase: emprendimiento.idEmprendimiento,
      idEmprendimiento: emprendimiento.idEmprendimiento,
      idFase: fase.idFase,
      fase: {
        idFase: fase.idFase,
        idEtapa: etapa.idEtapa,
        numero: fase.numero,
        nombre: fase.nombre,
        entregablesRequeridos: fase.entregableRequerido,
      },
      fechaInicio: emprendimiento.ultimaActividad,
      fechaFin: null,
      estadoFase: fase.estadoFase,
    },
  }
}
